    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {
        // create multiple accounts in text file then read
        String inputUser = loginUser.getText().trim();
        String inputPass = new String(loginPass.getPassword());

        // checks username and password
        if (inputUser.isEmpty() || inputUser.equals("Username")) {
            JOptionPane.showMessageDialog(this, "Please enter a username.");
        } else if (inputPass.isEmpty() || inputPass.equals("Password")) {
            JOptionPane.showMessageDialog(this, "Please enter a password.");
        } else {

            try {
                // reads accounts
                Scanner reader = new Scanner(FileManager.getAccountsFile());
                boolean accountFound = false;
                boolean isAdmin = false;

                while (reader.hasNextLine()) {
                    String line = reader.nextLine().trim();
                    String[] account = line.split(",", -1);

                    if (account.length != 3) {
                        continue;
                    }
                    //checks format
                    String savedUser = account[0].trim();
                    String savedPass = account[1].trim();
                    String savedRole = account[2].trim();

                    if (inputUser.equals(savedUser) && inputPass.equals(savedPass)) {

                        accountFound = true;

                        if (savedRole.equals("ADMIN")) {
                            isAdmin = true;
                        }

                        break;
                    }
                }

                reader.close();

                if (accountFound && isAdmin) {
                    AccountCreation accC = new AccountCreation();
                    accC.setVisible(true);
                    this.dispose();
                } else if (accountFound) {
                    Dashboard dashboard = new Dashboard();
                    dashboard.setVisible(true);
                    this.dispose();
                } else {
                    JOptionPane.showMessageDialog(this, "Invalid username or password.");
                    loginPass.setText("");
                }

            } catch (FileNotFoundException e) {
                System.out.println("Error: File Not Found.");
            }
        }

    }

    private void loginUserFocusGained(java.awt.event.FocusEvent evt) {
        // placeholder text
        if (loginUser.getText().equals("Username")) {
            loginUser.setText("");
            loginUser.setForeground(Color.WHITE);
        }
    }

    private void loginUserFocusLost(java.awt.event.FocusEvent evt) {
        // placeholder text
        if (loginUser.getText().trim().isEmpty()) {
            loginUser.setText("Username");
            loginUser.setForeground(Color.WHITE);
        }
    }

    private void loginPassFocusGained(java.awt.event.FocusEvent evt) {
        // placeholder text
        if (new String(loginPass.getPassword()).equals("Password")) {
            loginPass.setText("");
            loginPass.setForeground(Color.WHITE);

            if (btnShowPass.isSelected()) {
                loginPass.setEchoChar((char) 0);
            } else {
               loginPass.setEchoChar('*');
            }
        }
    }

    private void loginPassFocusLost(java.awt.event.FocusEvent evt) {
        // placeholder text
        if (loginPass.getPassword().length == 0) {
            loginPass.setEchoChar((char) 0);
            loginPass.setText("Password");
            loginPass.setForeground(Color.WHITE);
        }
    }

